#!/usr/bin/env python3
"""由 script_data.py 生成 29 画风口播脚本文档。
用法: python3 script_md.py <交付根>   →  交付根/脚本/29画风口播脚本.md
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import script_data as D

OUT = sys.argv[1]
mmss = lambda s: f'{int(s) // 60:02d}:{int(s) % 60:02d}'
b = D.BEATS
NG = len(D.S)
L = [f'# {D.TITLE}：这个我朋友能做吗', '',
     f'全片 {NG} 组，每组 8 秒，总长 {mmss(NG * 8)}，顺序是色序 v4（`色序/30画风播放顺序_v4.csv`）：从 {D.S[0]["id"]} {D.S[0]["name"]} 开场，沿原来的循环走到 S27，再接蓝图 S04，一直到 {D.S[-1]["id"]}。'
     f'9:16 画面顶栏常驻标题 {D.TITLE}，下面上层放 A、中层放 B，两段同步播 8 秒，底部是卡尔口播区。每一组都用同一套四拍结构，换画风的地方正好是 8 秒切点。', '',
     '## 每组 8 秒的固定节拍', '',
     '| 拍 | 组内时间 | 口播 | 屏幕 |', '|---|---|---|---|',
     f'| 问 | {b[0][0]:.1f}–{b[0][1]:.1f} s | 这个我朋友能做吗？ | 左栏弹出评论气泡，署名 @朋友 |',
     f'| 答 | {b[1][0]:.1f}–{b[1][1]:.1f} s | 能做，这个是某某画风。 | 气泡换成强调色画风名条，右侧带编号 |',
     f'| 提示语 | {b[2][0]:.1f}–{b[2][1]:.1f} s | 提示语这样写， | 提示语卡逐字打出，{D.TYPE_END:.1f} s 打完，之后一直留到本组结束 |',
     f'| 注意 | {b[3][0]:.1f}–{b[3][1]:.1f} s | 注意某某。 | 提示语卡下方出现注意条 |', '',
     '口播每组 37 到 45 个字，按每秒五个字左右的语速刚好落进 8 秒。屏幕上的提示语卡比口播长，观众要抄可以暂停。'
     '每组最后附的完整提示语是给朋友直接复制给 Opus 5.5 用的版本，在卡片句后面补了画面关键词、注意事项和输出规格。', '',
     f'排好的样片在 `脚本/{NG}画风口播排版_9x16.mp4`（1080×1920，30 fps，{NG * 8} s），右下是卡尔口播机位占位框，实拍后替换。每组的 A、B 效果和容易失败的点另见 `{NG}画风提示语对照表.md`。'
     '这份文档、对照表和样片都由 `源码/common/script_data.py` 一份数据生成，改字只改那一个文件，再跑 `script_md.py`、`prompt_table.py` 和 `script_layout.py`。', '']
for k, s in enumerate(D.S):
    t0 = k * 8
    q, a, p, n = D.spoken(s)
    L += [f'## {k + 1:02d}｜{mmss(t0)}–{mmss(t0 + 8)}｜{s["id"]} {s["name"]}', '',
          f'**口播**　{q}{a}{p}{n}', '',
          f'**提示语卡**　{s["card"]}', '',
          f'**注意条**　{s["warn"]}', '',
          f'**画面关键词**　{s["kw"]}', '',
          '**完整提示语（复制给 Opus 5.5）**', '', '```text', D.full_prompt(s), '```', '',
          f'依据：{s["basis"]}', '']
L += ['## 说明', '',
      'S13、S37、S35、S17、S02 这五组的来源页只有一两句话的提示词，没写画面规则，所以它们的关键词是对照下载下来的参考片补的，依据一栏已经注明观察。'
      'S37 的 B 和 S16 的 B 来自 x.com，这次没有读到原帖，提示语只依据同组 A 的来源。'
      '这次自己做的 13 组，关键词来自上游参考包里的上游开源提示语，再加上这次制作踩过的坑。'
      'S11 的 B 原例没有视频，这轮补做了一支孔版套印。'
      'S19、S04、S14、S03、S35、S07 的 B 原来也是同一个猫进村故事的日文讲解片，这轮各按自己的画风做了英文版，并把故事拆成几段：S07 种地存粮，S05 和 S19 老鼠引来野猫，S04 画成工程图，S14 做成科普卡，S03 人没赶猫，S35 收尾猫选择了人。黑白橡皮管 S25 已按要求去掉。', '']
os.makedirs(os.path.join(OUT, '脚本'), exist_ok=True)
dst = os.path.join(OUT, f'脚本/{NG}画风口播脚本.md'); open(dst, 'w').write('\n'.join(L)); print(dst, len(L))
